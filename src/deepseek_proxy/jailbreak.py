def get_jailbreak_prompt(name: Optional[str] = None) -> str:
    """获取指定名称的破限模板。

    Args:
        name: 模板名称，None 或 "off" 或空字符串返回空

    Returns:
        破限 system prompt 文本，为空则不注入
    """
    if not name:
        return ""
    name = name.strip().lower()
    # 精确匹配
    if name in JAILBREAK_TEMPLATES:
        return JAILBREAK_TEMPLATES[name]
    # 模糊匹配（不区分大小写）
    for key, value in JAILBREAK_TEMPLATES.items():
        if name in key.lower() or key.lower() in name:
            return value
    # 未匹配到则返回 default
    return JAILBREAK_TEMPLATES.get("default", "")


def list_templates() -> list[str]:
    """返回所有可用模板名称列表（不含 off）"""
    return [k for k in JAILBREAK_TEMPLATES if k != "off"]
